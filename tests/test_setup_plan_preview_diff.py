"""The setup preview is a patch: ``git apply`` must reproduce the change.

``setup plan --json`` publishes ``preview.unified_diff`` as a unified diff.
It was not one. Lines were split keeping their endings and then joined with
another newline, so every content line ended in two; git rejected the patch
as corrupt. A file that did not exist was diffed against one empty line,
which printed a removed line that was never there and a ``@@ -1 +1 @@``
header. The oracle here is independent of the producer: git applies the
preview to the file as it was, and the result must be byte for byte what the
setup apply would write.
"""

from __future__ import annotations

import json
import os
import subprocess
from pathlib import Path

import pytest

from tests._cli_child import child_env, run_codeclone


def _actions(tmp_path: Path, root: Path) -> dict[str, dict[str, object]]:
    run = run_codeclone(tmp_path, "setup", "plan", "--json", "--root", str(root))
    assert run.returncode == 0, run.stdout + run.stderr
    return {str(action["kind"]): action for action in json.loads(run.stdout)["actions"]}


def _preview(action: dict[str, object]) -> str:
    preview = action["preview"]
    assert isinstance(preview, dict)
    return str(preview["unified_diff"])


def _git_apply(directory: Path, patch: str, tmp_path: Path) -> None:
    env = child_env(tmp_path)
    env["GIT_CEILING_DIRECTORIES"] = os.fspath(directory.parent)
    applied = subprocess.run(
        ["git", "apply", "--unsafe-paths", "-"],
        cwd=directory,
        input=patch,
        env=env,
        text=True,
        capture_output=True,
        check=False,
    )
    assert applied.returncode == 0, (applied.stderr, patch)


def _project(tmp_path: Path, gitignore: bytes | None) -> Path:
    root = tmp_path / "proj"
    root.mkdir()
    (root / "mod.py").write_text("VALUE = 1\n", "utf-8")
    if gitignore is not None:
        (root / ".gitignore").write_bytes(gitignore)
    return root


@pytest.mark.parametrize(
    ("before", "after"),
    [
        pytest.param(b"venv/\n", b"venv/\n.codeclone/\n", id="trailing-newline"),
        pytest.param(b"venv/", b"venv/\n.codeclone/\n", id="no-trailing-newline"),
        pytest.param(b"", b".codeclone/\n", id="empty-file"),
        pytest.param(None, b".codeclone/\n", id="no-file"),
    ],
)
def test_the_gitignore_preview_applies_to_exactly_the_planned_file(
    tmp_path: Path, before: bytes | None, after: bytes
) -> None:
    root = _project(tmp_path, before)
    patch = _preview(_actions(tmp_path, root)["gitignore_append"])
    replay = tmp_path / "replay"
    replay.mkdir()
    if before is not None:
        (replay / ".gitignore").write_bytes(before)

    _git_apply(replay, patch, tmp_path)

    assert (replay / ".gitignore").read_bytes() == after
    # git also applies an ``a/`` header to a missing file, so the creation
    # marker is pinned by name: a new file is diffed from ``/dev/null``, an
    # existing one -- empty included -- from itself.
    source = "/dev/null" if before is None else "a/.gitignore"
    assert patch.startswith(f"--- {source}\n+++ b/.gitignore\n"), patch


def test_the_pyproject_preview_applies_to_the_planned_file(tmp_path: Path) -> None:
    """A plan merges into an existing ``pyproject.toml`` only; without one
    the plan is blocked, so there is no creation preview to check."""

    root = _project(tmp_path, b".codeclone/\n")
    before = b'[project]\nname = "demo"\n'
    (root / "pyproject.toml").write_bytes(before)
    patch = _preview(_actions(tmp_path, root)["pyproject_merge"])
    replay = tmp_path / "replay"
    replay.mkdir()
    (replay / "pyproject.toml").write_bytes(before)

    _git_apply(replay, patch, tmp_path)

    assert (replay / "pyproject.toml").read_bytes() == before + (
        b"\n[tool.codeclone]\n"
        b'baseline = "codeclone.baseline.json"\n'
        b'baseline_scope_id = "<generated by setup apply>"\n'
    )
