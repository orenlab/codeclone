"""Write, check or verify the exact install set of the CodeClone GitHub Action.

The Action installs the released ``codeclone`` wheel and its runtime
dependencies with ``pip install --require-hashes --only-binary :all:`` from
``.github/actions/codeclone/requirements.txt``. Every pin there comes from
``uv.lock`` (the runtime closure of ``[project] dependencies``, wheels only),
plus the SHA-256 of the release wheel itself, so a tag installs the same bytes
for as long as PyPI serves them.

Commands (run from the repository root, standard library only):

``write --wheel dist/codeclone-<version>-py3-none-any.whl``
    regenerate the file from ``uv.lock`` and the given release wheel;
``check``
    fail when the file differs from what ``uv.lock`` and ``pyproject.toml``
    imply (the codeclone hash is taken from the file itself);
``verify-wheel dist/codeclone-<version>-py3-none-any.whl``
    fail when the wheel is not the one the file pins (release gate).
"""

from __future__ import annotations

import argparse
import hashlib
import importlib
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

REQUIREMENTS_PATH = Path(".github/actions/codeclone/requirements.txt")
PROJECT = "codeclone"
HEADER = (
    "# Exact install set of the CodeClone GitHub Action: the release wheel and\n"
    "# its runtime dependencies from uv.lock, wheels only, every file pinned by\n"
    "# SHA-256. Installed with: pip install --require-hashes --only-binary :all:\n"
    "# Generated by scripts/action_requirements.py; do not edit by hand.\n"
)


@dataclass(frozen=True, slots=True)
class Pin:
    """One requirement line: name, exact version, marker and wheel hashes."""

    name: str
    version: str
    marker: str
    hashes: tuple[str, ...]

    def render(self) -> str:
        head = f"{self.name}=={self.version}"
        if self.marker:
            head += f" ; {self.marker}"
        lines = [head, *(f"    --hash=sha256:{digest}" for digest in self.hashes)]
        return " \\\n".join(lines) + "\n"


def _load_toml(path: Path) -> dict[str, Any]:
    # tomllib is stdlib from Python 3.11; on 3.10 codeclone already needs tomli.
    name = "tomllib" if sys.version_info >= (3, 11) else "tomli"
    loaded: dict[str, Any] = importlib.import_module(name).loads(
        path.read_text(encoding="utf-8")
    )
    return loaded


def _project_version(root: Path) -> str:
    return str(_load_toml(root / "pyproject.toml")["project"]["version"])


def _join_markers(markers: set[str]) -> str:
    if "" in markers:
        return ""
    if len(markers) == 1:
        return next(iter(markers))
    return " or ".join(f"({marker})" for marker in sorted(markers))


def runtime_pins(lock: dict[str, Any]) -> list[Pin]:
    """Return the runtime closure of the locked project as wheel-only pins."""

    packages: dict[str, list[dict[str, Any]]] = {}
    for package in lock["package"]:
        packages.setdefault(package["name"], []).append(package)
    root = packages[PROJECT][0]
    reached: dict[str, set[str]] = {}
    stack: list[tuple[str, str]] = [
        (dep["name"], dep.get("marker", "")) for dep in root.get("dependencies", [])
    ]
    while stack:
        name, marker = stack.pop()
        seen = reached.setdefault(name, set())
        if marker in seen:
            continue
        seen.add(marker)
        entries = packages[name]
        if len(entries) != 1:
            raise SystemExit(
                f"{name} has {len(entries)} locked versions; the Action set "
                "needs exactly one per runtime package"
            )
        for dep in entries[0].get("dependencies", []):
            inner = dep.get("marker", "")
            combined = " and ".join(part for part in (marker, inner) if part)
            stack.append((dep["name"], combined))
    pins = []
    for name in sorted(reached):
        entry = packages[name][0]
        hashes = tuple(
            sorted(wheel["hash"].removeprefix("sha256:") for wheel in entry["wheels"])
        )
        if not hashes:
            raise SystemExit(f"{name} {entry['version']} has no wheels in uv.lock")
        pins.append(Pin(name, entry["version"], _join_markers(reached[name]), hashes))
    return pins


def render(root: Path, wheel_sha256: str) -> str:
    """Render the requirements file for the project version and wheel hash."""

    lock = _load_toml(root / "uv.lock")
    pins = [
        Pin(PROJECT, _project_version(root), "", (wheel_sha256,)),
        *runtime_pins(lock),
    ]
    pins.sort(key=lambda pin: pin.name)
    return HEADER + "".join(pin.render() for pin in pins)


def pinned_wheel_sha256(text: str) -> str:
    """Return the single SHA-256 pinned for ``codeclone`` in the file text."""

    lines = text.splitlines()
    for index, line in enumerate(lines):
        if line.startswith(f"{PROJECT}=="):
            digest = lines[index + 1].strip().removeprefix("--hash=sha256:")
            return digest
    raise SystemExit(f"{REQUIREMENTS_PATH} pins no {PROJECT} wheel")


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _wheel_arg(value: str) -> Path:
    path = Path(value)
    if not path.is_file() or not path.name.endswith(".whl"):
        raise argparse.ArgumentTypeError(f"not a wheel file: {value}")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    write = sub.add_parser("write")
    write.add_argument("--wheel", type=_wheel_arg, required=True)
    sub.add_parser("check")
    verify = sub.add_parser("verify-wheel")
    verify.add_argument("wheel", type=_wheel_arg)
    args = parser.parse_args(argv)
    root = Path.cwd()
    target = root / REQUIREMENTS_PATH
    if args.command == "write":
        target.write_text(render(root, sha256_file(args.wheel)), encoding="utf-8")
        print(f"wrote {REQUIREMENTS_PATH}")
        return 0
    current = target.read_text(encoding="utf-8")
    regenerate = "python scripts/action_requirements.py write --wheel <wheel>"
    if args.command == "check":
        ok = current == render(root, pinned_wheel_sha256(current))
        message = (
            f"{REQUIREMENTS_PATH} matches uv.lock"
            if ok
            else f"{REQUIREMENTS_PATH} is out of date with uv.lock or "
            f"pyproject.toml; rebuild the release wheel and run: {regenerate}"
        )
    else:
        expected_name = f"{PROJECT}-{_project_version(root)}-py3-none-any.whl"
        actual = sha256_file(args.wheel)
        pinned = pinned_wheel_sha256(current)
        ok = args.wheel.name == expected_name and actual == pinned
        message = (
            f"{args.wheel.name} matches {REQUIREMENTS_PATH} ({actual})"
            if ok
            else f"Refusing to publish {args.wheel.name}: its SHA-256 is {actual}, "
            f"but {REQUIREMENTS_PATH} pins {expected_name} at {pinned}. Rebuild "
            "with the release build constraints and SOURCE_DATE_EPOCH, then run: "
            f"{regenerate}"
        )
    print(message, file=sys.stdout if ok else sys.stderr)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
